 assert.equal((await request('shifts/open',{opening:0},seller)).status,403);
 // Creating a seller cannot grant areas the manager lacks either.
 const limitedStaff=await request('users',{...identity,name:'Pedro Silva',bi:'009763935CA042',email:'limited@gmail.com',role:'vendedor'},manager);
