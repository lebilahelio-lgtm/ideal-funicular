 assert.equal((await request('users/access',access(staff.body.id,'vendedor',{products:'true'}))).status,400);
 assert.equal((await request('users/access',access(mgr.body.id,'gerente',{products:false,stock_edit:false,activity:false,fiscal:false,dashboard:false,history:false}))).status,200);
 assert.equal((await request('state',undefined,manager)).status,401);
 manager=(await request('login',{identifier:'manager@gmail.com',password:mgr.body.password})).cookie;
 const restricted=(await request('state',undefined,manager)).body;
