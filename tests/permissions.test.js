 assert.equal(restricted.products[0].pack_cost,undefined);
 assert.deepEqual(restricted.purchases,[]);assert.deepEqual(restricted.audit,[]);assert.deepEqual(restricted.chart,[]);assert.deepEqual(restricted.sales,[]);
 for(const path of ['stock','products','products/tax','fiscal/report'])assert.equal((await request(path,{},manager)).status,403);
 assert.equal((await request('users/access',access(mgr.body.id,'gerente',{stock_edit:true}),manager)).status,400);
 assert.equal((await request('users/access',access(staff.body.id,'vendedor',{products:true}),manager)).status,403);
 assert.equal((await request('users/access',access(staff.body.id,'vendedor',{products:false,dashboard:false,history:false}),manager)).status,200);
 assert.equal((await request('state',undefined,seller)).status,401);
 seller=(await request('login',{identifier:'seller@gmail.com',password:staff.body.password})).cookie;
 let state=(await request('state',undefined,seller)).body;
 assert.equal(state.user.permissions.products,false);assert.equal(state.user.permissions.sales,true);
 assert.deepEqual(state.users,[]);assert.deepEqual(state.audit,[]);assert.deepEqual(state.purchases,[]);
 assert.equal(state.products[0].stock,20);assert.equal(state.products[0].pack_cost,undefined);
 for(const path of ['stock','products','products/tax','users','users/access','users/remove','fiscal/report'])assert.equal((await request(path,{},seller)).status,403);
 assert.equal((await request('shifts/open',{opening:0},seller)).status,200);
 const receipt=await request('sales',{items:[{product_id:product.body.id,quantity:2}],discount:0,paid:200,method:'dinheiro'},seller);
